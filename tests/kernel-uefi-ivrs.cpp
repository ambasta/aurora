using Buffer = std::vector<std::byte>;
unsigned checks = 0;
auto check(bool value, const std::source_location location = std::source_location::current()) -> void {
    ++checks;
    if (!value) {
        std::cerr << "FAIL at line " << location.line() << ", check " << checks << '\n';
        std::abort();
    }
}
auto checksum(Buffer &bytes) -> void {
    bytes[9] = std::byte{};
    unsigned sum = 0;
    for (auto byte : bytes)
        sum += std::to_integer<unsigned>(byte);
    bytes[9] = std::byte(0U - sum);
}
auto repair(Buffer &bytes) -> void {
    put(bytes, 4, bytes.size(), 4);
    checksum(bytes);
}
auto hex_bytes(std::string_view text) -> Buffer {
    if (text.size() % 2)
        std::abort();
    Buffer result;
    const auto nibble = [](char c) -> unsigned {
        if (c >= '0' && c <= '9')
            return static_cast<unsigned>(c - '0');
        if (c >= 'a' && c <= 'f')
            return static_cast<unsigned>(c - 'a' + 10);
        std::abort();
    };
    for (std::size_t at = 0; at < text.size(); at += 2)
        result.push_back(std::byte((nibble(text[at]) << 4) | nibble(text[at + 1])));
    return result;
}
// Literal 168-byte table captured from the real QEMU 10.0.13 / q35 boot.
// QEMU tag v10.0.13, commit 98f88efe8f07067667b8d9b1a5ce9551d34036c1:
// hw/i386/acpi-build.c blob 3fffa4a332801c7f9780c49b1f5cfdbef3511c94,
// hw/i386/amd_iommu.c blob 8efebd3eea18335992d4f63df3503551e9787bab.
// Profile: pt=off,intremap=off,device-iotlb=off,xtsup=off. The firmware table
// is an independent wire fixture, not generated by the parser or fixture writer.
auto actual() -> Buffer {
    return hex_bytes("49565253a80000000112424f434853204258504320202020010000004258504301000000"
                     "01280000000000000000000010d13400180040000000d8fe000000000000000044000000"
                     "0200000002080000021000000218000002f8000002fa000002fb0000"
                     "11114400180040000000d8fe000000000000000000000000d3290000000000000000000000000000"
                     "0200000002080000021000000218000002f8000002fa000002fb0000");
}
auto parse(const Buffer &bytes, unsigned bits = 40) -> std::optional<Ivrs> {
    return Ivrs::parse_qemu_10_0_13(bytes, bits);
}
auto inventory() -> std::vector<PciFunction> {
    std::vector<PciFunction> result;
    for (unsigned id : {0U, 8U, 16U, 24U, 248U, 250U, 251U}) {
        PciFunction found{};
        found.bus = static_cast<std::uint8_t>(id >> 8);
        found.device = static_cast<std::uint8_t>((id >> 3) & 31);
        found.function = static_cast<std::uint8_t>(id & 7);
        found.vendor = 0x1234;
        found.device_id = 0x1111;
        if (id == 24) {
            found.vendor = 0x1022;
            found.device_id = 0x1419;
            found.class_code = 8;
            found.subclass = 6;
        }
        result.push_back(found);
    }
    return result;
}
auto sized(std::size_t count) -> Buffer {
    const auto original = actual();
    Buffer bytes(original.begin(), original.begin() + 48);
    for (auto type : {0x10U, 0x11U}) {
        const auto offset = type == 0x10 ? 48U : 100U, header = type == 0x10 ? 24U : 40U;
        const auto start = bytes.size();
        bytes.insert(bytes.end(), original.begin() + offset, original.begin() + offset + header);
        put(bytes, start + 2, header + count * 4, 2);
        for (std::size_t i = 0; i < count; ++i) {
            const auto at = bytes.size();
            bytes.resize(at + 4);
            put(bytes, at, 2, 1);
            put(bytes, at + 1, count == 1 ? 24 : i, 2);
        }
    }
    repair(bytes);
    return bytes;
}
// Same real boot's PCI header and the complete captured [0x40,0x70) region.
auto iommu_header() -> Buffer {
    return hex_bytes("2210191407001000000006080000000000000000000000000000000000000000"
                     "000000000000000000000000f41a0011000000006000000000000000ff000000");
}
auto iommu_capabilities() -> Buffer {
    return hex_bytes("0f00031f0000d8fe00000000000000ff40281800000000000540000008580000"
                     "055c8000000000000000000000000000");
}
auto iommu_snapshot(const Buffer &header, const Buffer &capabilities) -> std::optional<Q35IommuSnapshot> {
    return Q35IommuSnapshot::parse(0, 0, 3, 0, header, capabilities);
}
auto memory(unsigned type = 1, std::uint64_t begin = 0x400000, std::uint64_t pages = 256, std::uint64_t flags = 0)
    -> Buffer {
    Buffer bytes(40);
    put(bytes, 0, type, 4);
    put(bytes, 8, begin);
    put(bytes, 24, pages);
    put(bytes, 32, flags);
    return bytes;
}
auto reservation(std::uint64_t base, std::uint64_t length) -> std::optional<PciBarReservation> {
    Buffer header(64), descriptor(48);
    put(header, 0, 0x12345678, 4);
    put(header, 16, (base & 0xfffffff0) | 4, 4);
    put(header, 20, base >> 32, 4);
    const auto copied = PciBarSnapshot::parse(0, 0, 2, 0, header);
    if (!copied)
        std::abort();
    put(descriptor, 0, 0x8a, 1);
    put(descriptor, 1, 43, 2);
    put(descriptor, 6, 64);
    put(descriptor, 14, base);
    put(descriptor, 22, length - 1);
    put(descriptor, 38, length);
    put(descriptor, 46, 0x79, 2);
    return PciBarReservation::parse_edk2(*copied, *copied, 0, descriptor, 40);
}
auto check_admission(const Ivrs &ivrs) -> void {
    static_assert(!std::is_default_constructible_v<Q35IommuSnapshot>);
    static_assert(!std::is_default_constructible_v<Q35IommuReadPolicy>);
    static_assert(!std::is_convertible_v<Ivrs, Q35IommuReadPolicy>);
    static_assert(!std::is_convertible_v<Ivrs, NvmeBarGrant>);
    constexpr auto base = Q35IommuReadPolicy::base;
    const auto header = iommu_header(), capabilities = iommu_capabilities();
    check(header.size() == 64 && capabilities.size() == 48);
    const auto snapshot = iommu_snapshot(header, capabilities);
    check(snapshot && !snapshot->mmio_enabled() && snapshot->base() == base);
    for (std::size_t size = 0; size < header.size(); ++size)
        check(!Q35IommuSnapshot::parse(0, 0, 3, 0, std::span{header}.first(size), capabilities));
    for (std::size_t size = 0; size < capabilities.size(); ++size)
        check(!Q35IommuSnapshot::parse(0, 0, 3, 0, header, std::span{capabilities}.first(size)));
    auto longer = header;
    longer.push_back(std::byte{});
    check(!iommu_snapshot(longer, capabilities));
    longer = capabilities;
    longer.push_back(std::byte{});
    check(!iommu_snapshot(header, longer));
    for (auto tuple : {std::array{1U, 0U, 3U, 0U},
                       std::array{0U, 1U, 3U, 0U},
                       std::array{0U, 0U, 2U, 0U},
                       std::array{0U, 0U, 3U, 1U},
                       std::array{65536U, 256U, 32U, 8U}})
        check(!Q35IommuSnapshot::parse(tuple[0], tuple[1], tuple[2], tuple[3], header, capabilities));
    for (unsigned offset : {0U, 1U, 2U, 3U, 4U, 5U, 6U, 7U, 8U, 9U, 10U, 11U, 14U, 52U}) {
        for (unsigned bit = 0; bit < 8; ++bit) {
            auto wrong = header;
            wrong[offset] ^= std::byte(static_cast<unsigned char>(1U << bit));
            check(!iommu_snapshot(wrong, capabilities));
        }
    }
    for (std::size_t offset = 0; offset < capabilities.size(); ++offset) {
        for (unsigned bit = 0; bit < 8; ++bit) {
            auto wrong = capabilities;
            wrong[offset] ^= std::byte(static_cast<unsigned char>(1U << bit));
            check(iommu_snapshot(header, wrong).has_value() == (offset == 4 && bit == 0));
        }
    }
    auto copied_header = header, copied_capabilities = capabilities;
    const auto independently_copied = iommu_snapshot(copied_header, copied_capabilities);
    copied_header.assign(copied_header.size(), std::byte{});
    copied_capabilities.assign(copied_capabilities.size(), std::byte{});
    check(independently_copied && snapshot->same(*independently_copied));
    WindowAuthority authority, foreign;
    const auto ticket = authority.acquire(), foreign_ticket = foreign.acquire();
    check(ticket && foreign_ticket);
    auto map = memory();
    std::array<std::optional<PciBarReservation>, 1> bars{reservation(0xc0000000, 0x4000)};
    check(bars[0].has_value());
    const auto admit = [&](const Buffer &candidate, std::uint64_t arena = 0x400000, std::uint64_t apic = 0xfee00000) {
        return Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
            ivrs, *snapshot, *snapshot, candidate, 40, arena, apic, bars, authority, *ticket);
    };
    // Default refusal is independent and precedes explicit profile selection.
    check(!Q35IommuReadPolicy::authorize(
        ivrs, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
    auto admitted = admit(map);
    check(admitted && admitted->source() == IommuReadSource::Qemu10_0_13AmdViCold);
    auto enabled_bytes = capabilities;
    put(enabled_bytes, 4, base | 1, 4);
    const auto enabled = iommu_snapshot(header, enabled_bytes);
    check(enabled && enabled->mmio_enabled());
    const auto architectural = Q35IommuReadPolicy::authorize(
        ivrs, *enabled, *enabled, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket);
    check(architectural && architectural->source() == IommuReadSource::ArchitecturalEnable);
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *enabled, *enabled, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *snapshot, *enabled, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, bars, foreign, *ticket));
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, bars, authority, {}));
    // Exact snapshot equality includes uninterpreted header bytes.
    auto changed_header = header;
    changed_header[0x3c] ^= std::byte{1};
    const auto changed = iommu_snapshot(changed_header, capabilities);
    check(changed && !snapshot->same(*changed));
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *snapshot, *changed, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
    for (auto width : {0U, 1U, 2U, 4U, 8U, 16U, 255U})
        for (std::uint64_t offset = 0; offset < 0x4008; ++offset) {
            const bool allowed = width == 8 && (offset == 0x18 || offset == 0x30 || offset == 0x2020);
            const auto address = admitted->read_address(authority, *snapshot, offset, width);
            check(address.has_value() == allowed);
            if (address)
                check(*address == base + offset);
        }
    for (auto offset : {0ULL, 1ULL, 0x1000ULL, 0x2000ULL, 0x3000ULL, 0x4000ULL, ~0ULL}) {
        const auto page = admitted->page(authority, offset);
        check(page.has_value() == (offset == 0 || offset == 0x2000));
        if (page)
            check(*page == base + offset);
    }
    check(!admitted->read_address(authority, *snapshot, ~0ULL, 8));
    check(!admitted->read_address(authority, *changed, 0x18, 8));
    check(!admitted->read_address(foreign, *snapshot, 0x18, 8));
    check(!admitted->page(foreign, 0));
    check(admitted->finish(authority, *snapshot, 0, 0x29d3, 0));
    for (unsigned bit = 0; bit < 64; ++bit) {
        check(!admitted->finish(authority, *snapshot, 1ULL << bit, 0x29d3, 0));
        check(!admitted->finish(authority, *snapshot, 0, 0x29d3 ^ (1ULL << bit), 0));
        check(!admitted->finish(authority, *snapshot, 0, 0x29d3, 1ULL << bit));
    }
    check(!admitted->finish(authority, *changed, 0, 0x29d3, 0));
    for (unsigned type = 0; type <= 15; ++type)
        for (auto flags :
             {0ULL, 1ULL, 0x4000ULL, 0x20000ULL, 0x24001ULL, 2ULL, 4ULL, 8ULL, 0x1000ULL, 0x8000ULL, 1ULL << 63}) {
            const bool allowed = (type == 0 || type == 11) && !(flags & ~0x24001ULL);
            check(admit(memory(type, base, 4, flags)).has_value() == allowed);
        }
    for (unsigned bit = 0; bit < 64; ++bit)
        check(admit(memory(11, base, 4, 1ULL << bit)).has_value() == (bit == 0 || bit == 14 || bit == 17));
    // A forbidden page anywhere in the full aperture denies, including the two
    // pages which the adapter will never map for these three permitted reads.
    for (unsigned page = 0; page < 4; ++page)
        check(!admit(memory(1, base + page * 4096, 1)));
    check(admit(memory(1, base - 4096, 1)).has_value());
    check(admit(memory(1, base + 0x4000, 1)).has_value());
    check(!admit(memory(11, (1ULL << 40) - 4096, 2)));
    check(!admit(memory(11, ~0ULL - 4095, 1)));
    check(!admit(memory(11, base + 1, 1)));
    check(!admit(memory(11, base, 0)));
    check(!admit({}));
    auto overlap = memory(11, base, 4), second = memory(11, base + 4096, 1);
    overlap.insert(overlap.end(), second.begin(), second.end());
    check(!admit(overlap));
    for (auto stride : {0U, 8U, 39U, 41U, 264U})
        check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
            ivrs, *snapshot, *snapshot, map, stride, 0x400000, 0xfee00000, bars, authority, *ticket));
    for (auto arena : {base,
                       base + 0x3000,
                       base - Handoff::arena_bytes + 4096,
                       ~std::uint64_t{0} - 4095,
                       std::uint64_t{1} << 40,
                       std::uint64_t{0x400001}})
        check(!admit(map, arena));
    check(admit(map, base - Handoff::arena_bytes).has_value());
    check(admit(map, base + 0x4000).has_value());
    for (auto apic :
         {0ULL, 0xfee00001ULL, 1ULL << 40, ~0ULL - 4095, 0xfed80000ULL, 0xfed81000ULL, 0xfed82000ULL, 0xfed83000ULL})
        check(!admit(map, 0x400000, apic));
    check(admit(map, 0x400000, base - 4096).has_value());
    check(admit(map, 0x400000, base + 0x4000).has_value());
    for (std::uint64_t offset = 0; offset < 0x4000; offset += 4096) {
        bars[0] = reservation(base + offset, 4096);
        check(bars[0].has_value());
        check(!admit(map));
    }
    bars[0] = reservation(0xfed00000, 0x100000);
    check(bars[0].has_value());
    check(!admit(map));
    bars[0] = reservation(base - 0x4000, 0x4000);
    check(bars[0].has_value());
    check(admit(map).has_value());
    bars[0] = reservation(base + 0x4000, 0x4000);
    check(bars[0].has_value());
    check(admit(map).has_value());
    bars[0] = std::nullopt;
    check(!admit(map));
    bars[0] = reservation(0xc0000000, 0x4000);
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, {}, authority, *ticket));
    std::array<std::optional<PciBarReservation>, 10> too_many{};
    too_many.fill(bars[0]);
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        ivrs, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, too_many, authority, *ticket));
    for (unsigned field : {52U, 64U}) {
        auto wrong = actual();
        put(wrong, field, 1, 2);
        put(wrong, field + 52, 1, 2);
        checksum(wrong);
        const auto parsed = parse(wrong);
        if (field == 52)
            check(!parsed); // New unit ID lacks a SELECT claim.
        else {
            check(parsed.has_value());
            check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
                *parsed, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
        }
    }
    auto wrong = actual();
    put(wrong, 56, base + 0x4000);
    put(wrong, 108, base + 0x4000);
    checksum(wrong);
    const auto moved = parse(wrong);
    check(moved.has_value());
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        *moved, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
    wrong = actual();
    put(wrong, 81, 17, 2);
    put(wrong, 149, 17, 2);
    checksum(wrong);
    const auto missing_target = parse(wrong);
    check(missing_target.has_value());
    check(!Q35IommuReadPolicy::authorize_qemu_10_0_13_cold(
        *missing_target, *snapshot, *snapshot, map, 40, 0x400000, 0xfee00000, bars, authority, *ticket));
    check(authority.revoke(*ticket));
    check(!admitted->read_address(authority, *snapshot, 0x18, 8));
    check(!admitted->page(authority, 0));
    check(!admitted->finish(authority, *snapshot, 0, 0x29d3, 0));
    check(!admit(map));
    const auto next_ticket = authority.acquire();
    check(next_ticket.has_value());
    check(!admitted->read_address(authority, *snapshot, 0x18, 8));
    check(!admitted->page(authority, 0));
    check(authority.revoke(*next_ticket));
    check(foreign.revoke(*foreign_ticket));
}
auto main() -> int {
    static_assert(!std::is_default_constructible_v<Ivrs>);
    static_assert(std::is_same_v<decltype(std::declval<const Ivrs &>().requesters()), std::span<const std::uint16_t>>);
    static_assert(std::is_same_v<decltype(std::declval<const Ivrs &>().unit()), const IvrsUnit &>);
    const auto bytes = actual();
    check(bytes.size() == 168 && Acpi::checksum(bytes));
    auto parsed = parse(bytes);
    check(parsed.has_value());
    check(parsed->count() == 1 && parsed->record_count() == 2 && parsed->info() == 0x2801 &&
          parsed->physical_bits() == 40);
    const auto &unit = parsed->unit();
    check(unit.segment() == 0 && unit.device_id() == 24 && unit.capability_offset() == 0x40 &&
          unit.base() == 0xfed80000 && unit.length() == 0x4000 && unit.flags10() == 0xd1 && unit.flags11() == 0x11 &&
          unit.feature10() == 0x44 && unit.attributes() == 0 && unit.efr() == 0x29d3);
    constexpr std::array<std::uint16_t, 7> ids{0, 8, 16, 24, 248, 250, 251};
    check(std::equal(parsed->requesters().begin(), parsed->requesters().end(), ids.begin(), ids.end()));
    auto pci = inventory();
    check(parsed->matches_inventory(pci, 0, 0, 2, 0));
    for (auto id : ids)
        check(parsed->covers(0, id >> 8, (id >> 3) & 31, id & 7));
    for (auto tuple : {std::array{1U, 0U, 2U, 0U},
                       std::array{65536U, 0U, 2U, 0U},
                       std::array{0U, 256U, 2U, 0U},
                       std::array{0U, 0U, 32U, 0U},
                       std::array{0U, 0U, 2U, 8U},
                       std::array{0U, 0U, 2U, 1U},
                       std::array{0U, 255U, 31U, 7U}}) {
        check(!parsed->covers(tuple[0], tuple[1], tuple[2], tuple[3]));
        check(!parsed->matches_inventory(pci, tuple[0], tuple[1], tuple[2], tuple[3]));
    }
    auto changed = bytes;
    const auto copied = parse(changed);
    changed.assign(changed.size(), std::byte{});
    check(copied && copied->unit().base() == 0xfed80000 && copied->covers(0, 0, 2, 0));
    for (auto bits : {0U, 31U, 53U, 64U, 255U})
        check(!parse(bytes, bits));
    for (auto bits : {32U, 36U, 40U, 48U, 52U}) {
        check(parse(bytes, bits).has_value());
        changed = bytes;
        put(changed, 56, (1ULL << bits) - 0x4000);
        put(changed, 108, (1ULL << bits) - 0x4000);
        checksum(changed);
        check(parse(changed, bits).has_value());
        for (auto base : {0ULL, 1ULL, (1ULL << bits) - 4096, 1ULL << bits, ~0ULL - 0x3fff}) {
            changed = bytes;
            put(changed, 56, base);
            put(changed, 108, base);
            checksum(changed);
            check(!parse(changed, bits));
        }
    }
    for (std::size_t n = 0; n < bytes.size(); ++n)
        check(!Ivrs::parse_qemu_10_0_13(std::span{bytes}.first(n), 40));
    for (unsigned field : {0U,   1U,   2U,   3U,   4U,   5U,   6U,   7U,   8U,   36U,  37U,  38U,  39U,  40U,
                           41U,  42U,  43U,  44U,  45U,  46U,  47U,  49U,  54U,  55U,  66U,  67U,  68U,  69U,
                           70U,  71U,  101U, 106U, 107U, 118U, 119U, 120U, 121U, 122U, 123U, 124U, 125U, 126U,
                           127U, 128U, 129U, 130U, 131U, 132U, 133U, 134U, 135U, 136U, 137U, 138U, 139U}) {
        for (unsigned bit = 0; bit < 8; ++bit) {
            changed = bytes;
            changed[field] ^= std::byte(static_cast<unsigned char>(1U << bit));
            checksum(changed);
            check(!parse(changed));
        }
    }
    // A correct structural parse never repairs a failed checksum itself.
    for (std::size_t field = 0; field < bytes.size(); ++field) {
        changed = bytes;
        changed[field] ^= std::byte{1};
        check(!parse(changed));
    }
    // Common identity mismatches, including a different physical unit with the
    // same SELECT claims, must not produce two independently usable units.
    for (unsigned field = 104; field < 118; ++field) {
        changed = bytes;
        changed[field] ^= std::byte{1};
        checksum(changed);
        check(!parse(changed));
    }
    for (unsigned offset : {48U, 100U})
        for (unsigned length : {0U, 1U, 3U, 4U, 23U, 24U, 25U, 39U, 40U, 41U, 65535U}) {
            changed = bytes;
            put(changed, offset + 2, length, 2);
            checksum(changed);
            check(!parse(changed));
        }
    for (unsigned offset : {48U, 100U})
        for (unsigned type = 0; type < 256; ++type) {
            if (type == (offset == 48 ? 0x10U : 0x11U))
                continue;
            changed = bytes;
            put(changed, offset, type, 1);
            checksum(changed);
            check(!parse(changed));
        }
    for (unsigned offset : {72U, 140U})
        for (unsigned index = 0; index < 7; ++index) {
            for (unsigned type = 0; type < 256; ++type) {
                if (type == 2)
                    continue;
                changed = bytes;
                put(changed, offset + index * 4, type, 1);
                checksum(changed);
                check(!parse(changed));
            }
            for (unsigned bit = 0; bit < 8; ++bit) {
                changed = bytes;
                put(changed, offset + index * 4 + 3, 1U << bit, 1);
                checksum(changed);
                check(!parse(changed));
            }
            // Duplicate scope within either description is always ambiguous.
            changed = bytes;
            put(changed, offset + index * 4 + 1, ids[(index + 1) % 7], 2);
            checksum(changed);
            check(!parse(changed));
        }
    changed = bytes;
    put(changed, 141, 1, 2);
    checksum(changed);
    check(!parse(changed));
    // Both variants may be reordered without changing their semantic sets.
    changed = bytes;
    for (unsigned i = 0; i < 7; ++i)
        put(changed, 141 + i * 4, ids[6 - i], 2);
    checksum(changed);
    check(parse(changed).has_value());
    changed = Buffer(bytes.begin(), bytes.begin() + 48);
    changed.insert(changed.end(), bytes.begin() + 100, bytes.end());
    changed.insert(changed.end(), bytes.begin() + 48, bytes.begin() + 100);
    repair(changed);
    check(parse(changed).has_value());
    for (unsigned type : {0x10U, 0x11U}) {
        changed = bytes;
        const auto first = type == 0x10 ? 48U : 100U, last = type == 0x10 ? 100U : 168U;
        changed.insert(changed.end(), bytes.begin() + first, bytes.begin() + last);
        repair(changed);
        check(!parse(changed));
    }
    // Correctly sized IVMD forms are unsupported; no memory-exclusion promise
    // is silently discarded. Unknown trailing blocks likewise fail closed.
    for (unsigned type : {0U, 0x20U, 0x21U, 0x22U, 0xffU}) {
        changed = bytes;
        changed.resize(changed.size() + 32);
        put(changed, 168, type, 1);
        put(changed, 170, 32, 2);
        repair(changed);
        check(!parse(changed));
    }
    for (unsigned extra : {1U, 2U, 3U, 4U}) {
        changed = bytes;
        changed.resize(changed.size() + extra);
        repair(changed);
        check(!parse(changed));
    }
    check(!parse(sized(0)));
    check(parse(sized(1)).has_value());
    check(parse(sized(256)).has_value());
    check(!parse(sized(257)));
    // Removing the unit's own SELECT scope does not establish full coverage.
    changed = bytes;
    put(changed, 85, 25, 2);
    put(changed, 153, 25, 2);
    checksum(changed);
    check(!parse(changed));
    for (unsigned removed = 0; removed < 7; ++removed) {
        auto missing = pci;
        missing.erase(missing.begin() + removed);
        check(!parsed->matches_inventory(missing, 0, 0, 2, 0));
        auto duplicate = pci;
        duplicate[removed] = pci[(removed + 1) % 7];
        check(!parsed->matches_inventory(duplicate, 0, 0, 2, 0));
    }
    auto extra = pci;
    extra.push_back(pci.back());
    check(!parsed->matches_inventory(extra, 0, 0, 2, 0));
    for (unsigned id : {1U, 17U, 255U, 65535U}) {
        auto wrong = pci;
        wrong[2].bus = static_cast<std::uint8_t>(id >> 8);
        wrong[2].device = static_cast<std::uint8_t>((id >> 3) & 31);
        wrong[2].function = static_cast<std::uint8_t>(id & 7);
        check(!parsed->matches_inventory(wrong, 0, 0, 2, 0));
    }
    for (unsigned field = 0; field < 7; ++field) {
        auto wrong = pci;
        auto &iommu = wrong[3];
        if (field == 0)
            ++iommu.vendor;
        if (field == 1)
            ++iommu.device_id;
        if (field == 2)
            ++iommu.class_code;
        if (field == 3)
            ++iommu.subclass;
        if (field == 4)
            ++iommu.programming_interface;
        if (field == 5)
            ++iommu.header_type;
        if (field == 6)
            ++iommu.segment;
        check(!parsed->matches_inventory(wrong, 0, 0, 2, 0));
    }
    std::reverse(pci.begin(), pci.end());
    check(parsed->matches_inventory(pci, 0, 0, 2, 0));
    check_admission(*parsed);
    std::cout << "PASS: " << checks << " IVRS profile/pair/scope/boundary/read-only cases\n";
}
