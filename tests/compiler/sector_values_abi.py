#!/usr/bin/env python3
"""Independent private-ABI tests for owned 512-byte Blocks and 520-byte Reports.

Usage: sector_values_abi.py AURORA_IR_CHECK --air SECTOR_VALUES_AIR [--work-dir DIR]
       sector_values_abi.py AURORA_IR_CHECK --stack-guards [--work-dir DIR]
The fixture builds direct IR, never Aurora source. Every native execution has a
handwritten boundary side; protocol bytes and offsets below do not call any
production layout helper. Stack facts and probing are covered by the
stack-probes IR cases; --stack-guards runs the probes against real guard pages.
"""

import argparse
import os
import platform
from pathlib import Path
import re
import resource
import shutil
import subprocess
import tempfile

# Textual IR cases; the aurora-ir-check driver prints their assembly. The sector
# program is generated by tests/compiler/ir/abi_programs.py (--air).
STACK_PROBES = Path(__file__).resolve().parent / "ir" / "stack-probes" / "abi.air"


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def run(command, expected_exit=0):
    completed = subprocess.run(
        [str(part) for part in command],
        capture_output=True,
        timeout=60,
        preexec_fn=lambda: resource.setrlimit(resource.RLIMIT_CORE, (0, 0)),
    )
    require(
        completed.returncode == expected_exit,
        f"{command}: exit {completed.returncode}, stdout={completed.stdout!r}, stderr={completed.stderr!r}",
    )
    return completed.stdout


def report(record):
    status = (0x1100000000000000 + record).to_bytes(8, "little")
    payload = bytes((byte * 37 + record * 53 + (byte // 256) * 17) % 256 for byte in range(512))
    return status + payload


# Literal wire contract: status at 0, nested Block at 8, next Report at 520.
# Six canonical reservations total 3120, already aligned to 16. There is no
# additional return record. Result storage is independently pointed to.
RECORD = b"".join(report(record) for record in range(6))
RESULT = report(5)
BLOCK = RESULT[8:520]
require(len(RECORD) == 3120 and len(RESULT) == 520 and len(BLOCK) == 512, "literal protocol lengths")

ALIGN = """movq %rsp, %rcx
andq $15, %rcx
cmpq $8, %rcx
jne .Labi_fail
"""
POISON = """movq $-101, %rdi
movq $-102, %rsi
movq $-103, %rdx
movq $-104, %rcx
movq $-105, %r8
movq $-106, %r9
movq $-107, %rax
movq $-108, %r10
movq $-109, %r11
"""


def data(name, contents):
    return name + ":\n.byte " + ",".join(str(byte) for byte in contents) + "\n"


def body(assembly, symbol):
    pattern = rf"(?m)^{re.escape(symbol)}:\n([\s\S]*?)^\.size {re.escape(symbol)},[^\n]*\n"
    matches = re.findall(pattern, assembly)
    require(len(matches) == 1, f"exactly one fixture body {symbol}")
    return matches[0]


def replace(assembly, symbol, replacement):
    original = body(assembly, symbol)
    return assembly.replace(f"{symbol}:\n{original}.size {symbol},", f"{symbol}:\n{replacement}.size {symbol},", 1)


def compare_bytes(pointer, expected, size, label):
    return f"""movq {expected}, %rdi
xorq %rcx, %rcx
.Lcompare_{label}:
movzbq ({pointer},%rcx), %rsi
cmpb (%rdi,%rcx), %sil
jne .Labi_fail
incq %rcx
cmpq ${size}, %rcx
jne .Lcompare_{label}
"""


def disjoint(first, first_size, second, second_size, label):
    return f"""leaq {first_size}({first}), %r8
cmpq {second}, %r8
jbe .Ldisjoint_{label}
leaq {second_size}({second}), %r9
cmpq {first}, %r9
ja .Labi_fail
.Ldisjoint_{label}:
"""


def canaries():
    code = ""
    for pointer, size, left, right in [
        ("input_record", "record_size", 0x5252525252525252, 0x5353535353535353),
        ("result", "result_size", 0x6161616161616161, 0x6262626262626262),
    ]:
        code += f"movq {pointer}, %rdx\nmovabsq ${left:#x}, %rsi\ncmpq %rsi, -8(%rdx)\njne .Labi_fail\n"
        code += f"addq {size}, %rdx\nmovabsq ${right:#x}, %rsi\ncmpq %rsi, (%rdx)\njne .Labi_fail\n"
    for name, value in [("receiver_left", 0x7171717171717171), ("receiver_right", 0x7272727272727272)]:
        code += f"movabsq ${value:#x}, %rsi\ncmpq %rsi, {name}\njne .Labi_fail\n"
    return code


def independent_target(kind):
    size = 512 if kind == "block" else 520
    record_size = 512 if kind == "block" else 3120
    result_register = "%rax" if kind == "method" else "%r10"
    code = ALIGN + f"movq {result_register}, %rdx\n"
    # The record lies in the caller's live stack: above this call's return
    # address and below the caller's frame pointer (RBP is still the caller's).
    # Its exact position inside that frame is the caller's private layout.
    code += f"""testq $7, %rdx
jnz .Labi_fail
leaq 8(%rsp), %rsi
cmpq %rsi, %r11
jb .Labi_fail
leaq {record_size}(%r11), %rsi
cmpq %rbp, %rsi
ja .Labi_fail
"""
    code += disjoint("%rdx", size, "%r11", record_size, "result_record")
    if kind == "method":
        code += "cmpq $1000, (%r10)\njne .Labi_fail\n"
        code += disjoint("%rdx", size, "%r10", 8, "result_receiver")
        code += disjoint("%r10", 8, "%r11", record_size, "receiver_record")
    code += compare_bytes("%r11", "expected_record", record_size, "outgoing")
    code += f"""movq expected_result, %rdi
xorq %rcx, %rcx
.Lwrite_result:
movzbq (%rdi,%rcx), %rsi
movb %sil, (%rdx,%rcx)
incq %rcx
cmpq ${size}, %rcx
jne .Lwrite_result
"""
    return code + "movq $-111, %r10\nmovq $-112, %r11\nxorq %rax, %rax\nret\n"


def overwrite_original():
    return (
        ALIGN
        + """testq $2, case_flags
jz .Lclobber_done
movq input_record, %rdx
xorq %rcx, %rcx
.Loverwrite_original:
movb $165, (%rdx,%rcx)
incq %rcx
cmpq $3120, %rcx
jne .Loverwrite_original
.Lclobber_done:
movq $-111, %r10
movq $-112, %r11
movq $-113, %rax
ret
"""
    )


def native_cases():
    # name, emitted entry, input bytes, expected result, flags:
    # method receiver = 1, overwrite original after binding = 2, outgoing = 4.
    cases = []
    for kind in ["function", "constructor", "method"]:
        flags = 1 if kind == "method" else 0
        cases += [
            ("incoming-six-reports-" + kind, "sector_in_" + kind, RECORD, RESULT, flags),
            ("incoming-owned-snapshots-" + kind, "sector_in_" + kind, RECORD, RESULT, flags | 2),
            ("outgoing-six-reports-" + kind, "sector_out_" + kind, RECORD, RESULT, 4),
        ]
    cases += [
        ("incoming-512-byte-block", "sector_in_block", BLOCK, BLOCK, 0),
        ("outgoing-512-byte-block", "sector_out_block", BLOCK, BLOCK, 4),
    ]
    # Noncanonical padding is deliberately different on either side. Payload
    # lowering must neither import the caller's poisoned gaps nor overwrite the
    # result's untouched gaps, even beside nested unaligned U8 runs.
    mixed_input = bytearray([165] * 48)
    mixed_result = bytearray([204] * 48)
    for offset in (*range(11), *range(40, 47)):
        mixed_input[offset] = mixed_result[offset] = (offset * 37 + 131) % 256
    for offset, value in ((16, 1), (24, 1), (32, (1 << 64) - 1)):
        mixed_input[offset : offset + 8] = value.to_bytes(8, "little")
        mixed_result[offset : offset + 8] = value.to_bytes(8, "little")
    cases.append(("mixed-width-poisoned-padding-and-canaries", "sector_in_mixed", mixed_input, mixed_result, 0))
    gap_input = bytearray([165] * 24)
    gap_result = bytearray([204] * 24)
    gap_input[0:8] = gap_result[0:8] = ((1 << 64) - 1).to_bytes(8, "little")
    for offset in (*range(8, 15), 16):
        gap_input[offset] = gap_result[offset] = (offset * 37 + 131) % 256
    cases.append(("eight-logical-bytes-split-by-poisoned-gap", "sector_in_gap", gap_input, gap_result, 0))
    return cases


def native_driver(assembly, work):
    cases = native_cases()
    assembly = replace(assembly, "sector_clobber", overwrite_original())
    for kind in ["function", "constructor", "method", "block"]:
        target = independent_target(kind)
        # Each handwritten boundary has private loop labels in the shared object.
        target = re.sub(r"\.L(?!abi_fail\b)(\w+)", rf".L{kind}_\1", target)
        assembly = replace(assembly, "sector_target_" + kind, target)
    # Linux's initial stack supplies argv[1], a decimal case index. Every case
    # gets a fresh process, but all share this one emitted and linked program.
    assembly += f"""
.text
.globl _start
_start:
cmpq $2, (%rsp)
jne .Labi_fail
movq 16(%rsp), %rsi
xorq %rax, %rax
.Lcase_number:
movzbq (%rsi), %rdx
testq %rdx, %rdx
jz .Lcase_selected
subq $48, %rdx
cmpq $9, %rdx
ja .Labi_fail
imulq $10, %rax
addq %rdx, %rax
cmpq ${len(cases)}, %rax
jae .Labi_fail
incq %rsi
jmp .Lcase_number
.Lcase_selected:
shlq $6, %rax
leaq case_table(%rax), %rsi
leaq case_target, %rdi
movq $8, %rcx
rep movsq
{POISON}
movq input_record, %r11
testq $4, case_flags
jnz .Lcall
movq result, %r10
testq $1, case_flags
jz .Lcall
leaq receiver, %r10
movq result, %rax
.Lcall:
call *case_target
testq $4, case_flags
jz .Lcheck_result
cmpq $43, %rax
jne .Labi_fail
jmp .Lcheck_canaries
.Lcheck_result:
movq result, %rdx
movq expected_result, %rdi
xorq %rcx, %rcx
.Lresult_bytes:
movzbq (%rdx,%rcx), %rsi
cmpb (%rdi,%rcx), %sil
jne .Labi_fail
incq %rcx
cmpq result_size, %rcx
jne .Lresult_bytes
.Lcheck_canaries:
{canaries()}
movq $60, %rax
xorq %rdi, %rdi
syscall
.Labi_fail:
movq $60, %rax
movq $91, %rdi
syscall
.data
.balign 16
receiver_left: .quad 0x7171717171717171
receiver: .quad 1000
receiver_right: .quad 0x7272727272727272
case_target: .quad 0
input_record: .quad 0
expected_record: .quad 0
expected_result: .quad 0
result: .quad 0
record_size: .quad 0
result_size: .quad 0
case_flags: .quad 0
case_table:
"""
    for number, (_, entry, record, result, flags) in enumerate(cases):
        assembly += (
            f".quad {entry}, input_{number}, record_{number}, expected_{number}, result_{number}, "
            f"{len(record)}, {len(result)}, {flags}\n"
        )
    for number, (_, _, record, result, _) in enumerate(cases):
        assembly += ".balign 8\n.quad 0x5252525252525252\n" + data(f"input_{number}", record)
        assembly += ".quad 0x5353535353535353\n"
        assembly += data(f"record_{number}", record) + data(f"expected_{number}", result)
        assembly += f""".balign 8
.quad 0x6161616161616161
result_{number}: .fill {len(result)},1,204
.quad 0x6262626262626262
"""
    assembly += '.section .note.GNU-stack,"",@progbits\n'
    (work / "program.s").write_text(assembly)
    run(["as", "--64", work / "program.s", "-o", work / "program.o"])
    symbols = run(["nm", work / "program.o"]).decode()
    for kind in ["function", "constructor", "method", "block"]:
        for prefix in ["sector_in_", "sector_out_", "sector_target_"]:
            symbol = prefix + kind
            require(re.search(rf"\bt {symbol}$", symbols, re.M), f"{symbol} lost private binding")
    run(["ld", "-o", work / "program", work / "program.o"])
    for number, (name, *_data) in enumerate(cases):
        run([work / "program", number])
        print("PASS sector ABI", name, flush=True)
    return len(cases)


def label_guard_probes(assembly):
    """Add only symbol metadata at real emitted probes; never change instructions.
    stack_guards.c names, by ordinal, the probe each guard case must fault at: a
    missing probe fails the link and a misplaced one fails its case."""
    symbols = [f"guard_frame_{size}" for size in (4080, 4096, 4112, 8192, 65536)]
    symbols += ["guard_target", "guard_call_even", "guard_call_odd", "guard_recursive"]
    labeled = assembly
    for symbol in symbols:
        modified = []
        probes = 0
        for line in body(assembly, symbol).splitlines(keepends=True):
            if line == "    orq $0, (%rsp)\n":
                probes += 1
                label = f"guard_probe_{symbol}_{probes}"
                modified.extend([f".globl {label}\n", f"{label}:\n"])
            modified.append(line)
        labeled = replace(labeled, symbol, "".join(modified))
    stripped = re.sub(r"(?m)^\.globl (guard_probe_\w+)\n\1:\n", "", labeled)
    require(stripped == assembly, "guard labeling changed emitted instructions or other metadata")
    return labeled


def stack_guard_cases(fixture, work):
    # Fail closed before generating/building anything on an unsupported host.
    require(
        platform.system() == "Linux" and platform.machine() == "x86_64" and os.sysconf("SC_PAGE_SIZE") == 4096,
        "stack guards require x86-64 Linux with 4096-byte pages",
    )
    assembly = run([fixture, "--output", STACK_PROBES, "guard-fixtures"]).decode()
    require(0 < len(assembly.encode()) < 128 * 1024, "unexpected guard-fixture assembly extent")
    (work / "guard-emitted.s").write_text(assembly)
    (work / "guard-labeled.s").write_text(label_guard_probes(assembly))
    sources = Path(__file__).resolve().parent
    # One executable is shared by the finite cases, not the large sector corpus.
    # Existing run() supplies each subprocess's timeout and core0 soft/hard cap;
    # the externally admitted native lane still owns its existing artifact caps.
    run(
        [
            "gcc",
            "-std=c11",
            "-O2",
            "-Wall",
            "-Wextra",
            "-Wpedantic",
            "-Werror",
            "-fno-omit-frame-pointer",
            "-fno-stack-protector",
            "-no-pie",
            "-Wl,-z,now",
            "-Wl,-z,noexecstack",
            sources / "stack_guards.c",
            sources / "stack_guards.S",
            work / "guard-labeled.s",
            "-o",
            work / "stack-guards",
        ]
    )
    cases = (
        "fit-subpage",
        "fit-page",
        "fit-tail",
        "fit-two-page",
        "fit-max",
        "guard-page",
        "guard-tail",
        "guard-two-page",
        "guard-max",
        "fit-cumulative-even",
        "fit-cumulative-odd",
        "guard-cumulative-even",
        "guard-cumulative-odd",
        "fit-recursion",
        "guard-recursion",
    )
    for name in cases:
        run([work / "stack-guards", name])
        print("PASS stack guard", name, flush=True)
    print(
        f"PASS stack guards: {len(cases)} disposable-child cases; probe PC/address, alternate stack, "
        "full landing canaries and return/register restoration checked",
        flush=True,
    )


def sector_abi_cases(fixture, air, work):
    assembly = run([fixture, "--output", air, "abi"]).decode()
    (work / "fixture.s").write_text(assembly)
    count = native_driver(assembly, work)
    print(f"PASS sector ABI: {count} independent native cases; all payload bytes and status checked", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fixture", type=Path)
    parser.add_argument("--work-dir", type=Path)
    parser.add_argument("--air", type=Path, help="generated sector-values program (required without --stack-guards)")
    parser.add_argument(
        "--stack-guards", action="store_true", help="run only disposable-child stack guards using PREBUILT_STACK_PROBES"
    )
    args = parser.parse_args()
    if not args.stack_guards and args.air is None:
        parser.error("--air is required for the sector ABI cases")
    fixture = args.fixture.resolve()
    work = args.work_dir.resolve() if args.work_dir else Path(tempfile.mkdtemp(prefix="aurora-sector-abi-"))
    work.mkdir(parents=True, exist_ok=True)
    print(f"work directory: {work}", flush=True)
    try:
        if args.stack_guards:
            stack_guard_cases(fixture, work)
        else:
            sector_abi_cases(fixture, args.air.resolve(), work)
    except Exception:
        print(f"FAIL: retained ABI artifacts in {work}", flush=True)
        raise
    else:
        if not args.work_dir:
            shutil.rmtree(work)


if __name__ == "__main__":
    main()
