#!/usr/bin/env python3
"""Independent direct-IR short-circuit and private-ABI native acceptance.

A textual IR case supplies verified IR and emitted instructions, never expectations.
Handwritten assembly replaces only probe bodies and metadata helper bodies. It
checks actual entry RSP modulo 16, record payloads, receiver authority, span
bounds/data and class-result storage. Each executed probe counts an effect;
method probes additionally mutate a real receiver field. Full 64-bit results
are read through the shared freestanding signal/syscall bridge.

A probe that sees a wrong alignment or argument stops at its own named UD2.
Every wrapper is linked into one binary: one run checks all value/effect cases
and each required-RHS trap runs once from argv (native_runner.py). These are
bounded bootstrap ABI observations, not a public Aurora ABI or a safety proof.
"""

from __future__ import annotations

import argparse
from enum import Enum
import itertools
from pathlib import Path
import re
import tempfile

from native_runner import Freestanding, check_trap, check_words, command, freestanding_glue, observe, require, run
from native_runner import symbols_of

# The program is generated by tests/compiler/ir/abi_programs.py (--air); the
# aurora-ir-check driver prints its assembly.


class ProbeTrap(Enum):
    ALIGNMENT = ".Lsc_alignment_trap"
    ARGUMENT = ".Lsc_argument_trap"
    BOUNDS = ".Laurora_bounds_trap"
    OVERFLOW = ".Laurora_overflow_trap"
    ZERO = ".Laurora_division_zero_trap"
    SHIFT = ".Laurora_shift_count_trap"


KINDS = (
    "scalar",
    "aggregate",
    "aggregate_result",
    "method",
    "method_value",
    "method_result",
    "metadata",
    "span",
    "subspan",
)
PREFIX = (1 << 40) + 17


def align_check():
    # At a SysV-style x86-64 function entry the return address accounts for
    # eight bytes. No prologue, compiler-generated or handwritten, precedes it.
    return """    movq %rsp, %rcx
    andq $15, %rcx
    cmpq $8, %rcx
    jne .Lsc_alignment_trap
"""


def replace_body(assembly, symbol, body):
    pattern = rf"(^{re.escape(symbol)}:\n).*?(^\.size {re.escape(symbol)},[^\n]*\n)"
    result, count = re.subn(pattern, lambda match: match[1] + body + match[2], assembly, flags=re.MULTILINE | re.DOTALL)
    require(count == 1, f"expected exactly one generated body for {symbol}, got {count}")
    return result


def instrument(assembly):
    for kind in KINDS:
        if kind in ("metadata", "subspan"):
            continue
        body = align_check()
        if kind.startswith("method"):
            body += """    cmpq $23, 0(%r10)
    jne .Lsc_argument_trap
    cmpq $29, 8(%r10)
    jb .Lsc_argument_trap
    cmpq $30, 8(%r10)
    ja .Lsc_argument_trap
    incq 8(%r10)
"""
        if kind in ("aggregate", "aggregate_result", "method_value", "method_result"):
            body += """    cmpq $17, 0(%r11)
    jne .Lsc_argument_trap
    cmpq $19, 8(%r11)
    jne .Lsc_argument_trap
    movq 16(%r11), %rdx
    cmpq $1, %rdx
    ja .Lsc_argument_trap
"""
            if kind == "aggregate_result":
                body += "    movq %rdx, 0(%r10)\n    movq $0, 8(%r10)\n"
            elif kind == "method_result":
                body += "    movq %rdx, 0(%rax)\n    movq $0, 8(%rax)\n"
            else:
                body += "    movq %rdx, %rax\n"
        elif kind == "span":
            body += """    cmpq $0, 0(%r11)
    jne .Lsc_argument_trap
    cmpq $0, 16(%r11)
    jne .Lsc_argument_trap
    cmpq $0, 24(%r11)
    jne .Lsc_argument_trap
    cmpq $0, 32(%r11)
    jne .Lsc_argument_trap
    movq 8(%r11), %rdx
    addq 40(%r11), %rdx
    cmpq $3, 48(%r11)
    je .Lsc_full_span
    cmpq $1, 48(%r11)
    jne .Lsc_argument_trap
    cmpq $1, 40(%r11)
    jne .Lsc_argument_trap
    cmpb $22, 0(%rdx)
    jne .Lsc_argument_trap
    jmp .Lsc_span_boolean
.Lsc_full_span:
    cmpq $0, 40(%r11)
    jne .Lsc_argument_trap
    cmpb $11, 0(%rdx)
    jne .Lsc_argument_trap
    cmpb $22, 1(%rdx)
    jne .Lsc_argument_trap
    cmpb $33, 2(%rdx)
    jne .Lsc_argument_trap
.Lsc_span_boolean:
    movq 56(%r11), %rax
    cmpq $1, %rax
    ja .Lsc_argument_trap
"""
        else:
            body += """    movq %rdi, %rax
    cmpq $1, %rax
    ja .Lsc_argument_trap
"""
        body += "    incq sc_probe_count(%rip)\n    ret\n"
        assembly = replace_body(assembly, "sc_probe_" + kind, body)
    metadata = (
        align_check()
        + """    xorq %rax, %rax
    cmpq $18, %rdi
    je .Lsc_metadata_done
    cmpq $17, %rdi
    jne .Lsc_argument_trap
    movq $1, %rax
.Lsc_metadata_done:
    incq sc_probe_count(%rip)
    ret
"""
    )
    assembly = replace_body(assembly, "aurora_reflect_size", metadata)
    return (
        assembly
        + """
.data
.align 8
sc_probe_count:
    .quad 0
.text
.Lsc_alignment_trap:
    ud2
.Lsc_argument_trap:
    ud2
"""
    )


def model(shape, a, b, c):
    """Closed independent truth/effect model, with no compiler data as input."""
    if shape == "and":
        return bool(a and b), int(bool(a))
    if shape == "or":
        return bool(a or b), int(not a)
    require(shape == "nested", f"unknown shape {shape}")
    first = bool(a and b)
    return bool(first or c), int(bool(a)) + int(not first)


def wrapper(name, target, values, encoded=True):
    # The runner calls this wrapper with entry RSP%16 == 8. Its own explicit
    # alignment adjustment is independent of the generated caller under test.
    a, b, c = values
    result = f"""
.text
.globl {name}
{name}:
    movq $0, sc_probe_count(%rip)
    movq ${a}, %rdi
    movq ${b}, %rsi
    movq ${c}, %rdx
    subq $8, %rsp
    call {target}
    addq $8, %rsp
"""
    if encoded:
        result += "    imulq $1000, %rax\n    addq sc_probe_count(%rip), %rax\n"
    return result + "    ret\n"


def cases():
    tests = []
    for kind, shape, depth, values in itertools.product(
        KINDS, ("and", "or", "nested"), range(4), itertools.product((0, 1), repeat=3)
    ):
        truth, effects = model(shape, *values)
        result = sum(PREFIX + index for index in range(depth)) + int(truth)
        if kind.startswith("method"):
            result += 100 * (29 + effects)
        expected = result * 1000 + effects
        target = f"sc_{kind}_{shape}_{depth}"
        name = f"{target}{values}"
        tests.append((target, values, expected, name))
    for target in ("sc_guarded_store", "sc_receiver_guarded_store", "sc_window_count"):
        for values in itertools.product((0, 1), repeat=3):
            truth, effects = model("nested", *values)
            tests.append((target, values, int(truth) * 1000 + effects, f"{target}{values}"))
    for trap, shape, depth in itertools.product(("bounds", "overflow", "zero", "shift"), ("and", "or"), (1, 2)):
        target = f"sc_trap_{trap}_{shape}_{depth}"
        skip = int(shape == "or")
        value = (sum(PREFIX + index for index in range(depth)) + skip) * 1000
        tests.append((target, (skip, 0, 0), value, f"skipped {target}"))
    return tests


def required_traps():
    for trap, shape, depth in itertools.product(("bounds", "overflow", "zero", "shift"), ("and", "or"), (1, 2)):
        yield f"sc_trap_{trap}_{shape}_{depth}", ProbeTrap[trap.upper()]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ir_tests", type=Path)
    parser.add_argument("--air", type=Path, required=True, help="generated short-circuit program")
    arguments = parser.parse_args()
    raw = command([arguments.ir_tests.resolve(), "--output", arguments.air, "native"], timeout=30).stdout.decode()
    require("validated typed IR" in raw, "fixture did not emit validated assembly")
    tests = cases()
    names = [name for _, _, _, name in tests]
    expected = [result for _, _, result, _ in tests]
    wrappers = [wrapper(f"sc_case_{index}", target, values) for index, (target, values, _, _) in enumerate(tests)]
    entries = [f"sc_case_{index}" for index in range(len(tests))]
    traps = list(required_traps())
    for number, (target, _) in enumerate(traps):
        # Executing the required right-hand side must stop at its exact trap.
        wrappers.append(wrapper(f"sc_required_trap_{number}", target, (int("_and_" in target), 0, 0)))
        entries.append(f"sc_required_trap_{number}")
    with tempfile.TemporaryDirectory(prefix="aurora-short-circuit-ir-") as temporary:
        directory = Path(temporary)
        program = directory / "all-cases.s"
        program.write_text(
            instrument(raw) + "\n".join(wrappers) + freestanding_glue(entries, range(len(tests)), note=True)
        )
        command(["as", "--64", "-L", program, "-o", directory / "all-cases.o"])
        harness = Freestanding()
        harness.prepare(directory)
        binary = directory / "all-cases"
        harness.link([directory / "all-cases.o"], binary)
        check_words(observe(run([binary], 10)), expected, names)
        symbols = symbols_of(binary)
        for number, (target, trap) in enumerate(traps):
            check_trap(observe(run([binary, len(tests) + number], 10)), trap, symbols, target)
    print(
        f"PASS short-circuit direct IR native: {len(tests)} value/effect cases; "
        "9 call kinds, 4 retained stack depths, full truth tables; "
        f"{len(traps)} exact required-RHS traps; one link"
    )


if __name__ == "__main__":
    main()
